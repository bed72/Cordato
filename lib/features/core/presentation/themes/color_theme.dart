import 'package:material_ui/material_ui.dart';

@immutable
class const AppColors({
  required final Color background,
  required final Color surface,
  required final Color surfaceSubtle,
  required final Color field,
  required final Color text,
  required final Color textMuted,
  required final Color textOnPrimary,
  required final Color primary,
  required final Color primarySoft,
  required final Color selection,
  required final Color border,
  required final Color borderSubtle,
  required final Color success,
  required final Color textOnSuccess,
  required final Color error,
  required final Color textOnError,
  required final Color errorSoft,
  required final Color textOnErrorSoft,
  required final Color info,
  required final Color textOnInfo,
  required final Color warning,
  required final Color textOnWarning,
}) extends ThemeExtension<AppColors> {
  @override
  AppColors copyWith({
    Color? background,
    Color? surface,
    Color? surfaceSubtle,
    Color? field,
    Color? text,
    Color? textMuted,
    Color? textOnPrimary,
    Color? primary,
    Color? primarySoft,
    Color? selection,
    Color? border,
    Color? borderSubtle,
    Color? success,
    Color? textOnSuccess,
    Color? error,
    Color? textOnError,
    Color? errorSoft,
    Color? textOnErrorSoft,
    Color? info,
    Color? textOnInfo,
    Color? warning,
    Color? textOnWarning,
  }) => AppColors(
    background: background ?? this.background,
    surface: surface ?? this.surface,
    surfaceSubtle: surfaceSubtle ?? this.surfaceSubtle,
    field: field ?? this.field,
    text: text ?? this.text,
    textMuted: textMuted ?? this.textMuted,
    textOnPrimary: textOnPrimary ?? this.textOnPrimary,
    primary: primary ?? this.primary,
    primarySoft: primarySoft ?? this.primarySoft,
    selection: selection ?? this.selection,
    border: border ?? this.border,
    borderSubtle: borderSubtle ?? this.borderSubtle,
    success: success ?? this.success,
    textOnSuccess: textOnSuccess ?? this.textOnSuccess,
    error: error ?? this.error,
    textOnError: textOnError ?? this.textOnError,
    errorSoft: errorSoft ?? this.errorSoft,
    textOnErrorSoft: textOnErrorSoft ?? this.textOnErrorSoft,
    info: info ?? this.info,
    textOnInfo: textOnInfo ?? this.textOnInfo,
    warning: warning ?? this.warning,
    textOnWarning: textOnWarning ?? this.textOnWarning,
  );

  @override
  AppColors lerp(ThemeExtension<AppColors>? other, double t) =>
      other is! AppColors
      ? this
      : AppColors(
          background: Color.lerp(background, other.background, t)!,
          surface: Color.lerp(surface, other.surface, t)!,
          surfaceSubtle: Color.lerp(surfaceSubtle, other.surfaceSubtle, t)!,
          field: Color.lerp(field, other.field, t)!,
          text: Color.lerp(text, other.text, t)!,
          textMuted: Color.lerp(textMuted, other.textMuted, t)!,
          textOnPrimary: Color.lerp(textOnPrimary, other.textOnPrimary, t)!,
          primary: Color.lerp(primary, other.primary, t)!,
          primarySoft: Color.lerp(primarySoft, other.primarySoft, t)!,
          selection: Color.lerp(selection, other.selection, t)!,
          border: Color.lerp(border, other.border, t)!,
          borderSubtle: Color.lerp(borderSubtle, other.borderSubtle, t)!,
          success: Color.lerp(success, other.success, t)!,
          textOnSuccess: Color.lerp(textOnSuccess, other.textOnSuccess, t)!,
          error: Color.lerp(error, other.error, t)!,
          textOnError: Color.lerp(textOnError, other.textOnError, t)!,
          errorSoft: Color.lerp(errorSoft, other.errorSoft, t)!,
          textOnErrorSoft: Color.lerp(
            textOnErrorSoft,
            other.textOnErrorSoft,
            t,
          )!,
          info: Color.lerp(info, other.info, t)!,
          textOnInfo: Color.lerp(textOnInfo, other.textOnInfo, t)!,
          warning: Color.lerp(warning, other.warning, t)!,
          textOnWarning: Color.lerp(textOnWarning, other.textOnWarning, t)!,
        );
}

